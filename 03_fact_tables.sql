USE DATABASE SMK_MANUFACTURING_DB;

CREATE TABLE FACT_PRODUCTION (
    PRODUCTION_ID BIGINT PRIMARY KEY,
    
    DATE_KEY INTEGER,
    PLANT_ID INTEGER,
    LINE_ID INTEGER,
    MACHINE_ID INTEGER,
    PRODUCT_ID INTEGER,
    SHIFT_ID INTEGER,

    PLANNED_QTY INTEGER,
    PRODUCED_QTY INTEGER,
    GOOD_QTY INTEGER,
    REJECTED_QTY INTEGER,

    PRODUCTION_HOURS DECIMAL(10,2),
    PRODUCTION_COST DECIMAL(14,2)
);

CREATE TABLE FACT_PRODUCTION_TARGET (
    TARGET_ID BIGINT PRIMARY KEY,

    DATE_KEY INTEGER,
    PLANT_ID INTEGER,
    LINE_ID INTEGER,
    PRODUCT_ID INTEGER,

    TARGET_QTY INTEGER,
    TARGET_COST DECIMAL(14,2)
);


CREATE TABLE FACT_QUALITY (
    QUALITY_ID BIGINT PRIMARY KEY,

    DATE_KEY INTEGER,
    PLANT_ID INTEGER,
    LINE_ID INTEGER,
    MACHINE_ID INTEGER,
    PRODUCT_ID INTEGER,

    INSPECTION_COUNT INTEGER,
    PASSED_COUNT INTEGER,
    FAILED_COUNT INTEGER,
    DEFECT_QTY INTEGER,

    DEFECT_TYPE VARCHAR(50),
    DEFECT_COST DECIMAL(14,2)
);


 CREATE TABLE FACT_DOWNTIME (
    DOWNTIME_ID BIGINT PRIMARY KEY,

    DATE_KEY INTEGER,
    PLANT_ID INTEGER,
    LINE_ID INTEGER,
    MACHINE_ID INTEGER,

    DOWNTIME_START TIMESTAMP,
    DOWNTIME_END TIMESTAMP,

    DOWNTIME_MINUTES INTEGER,

    DOWNTIME_REASON VARCHAR(100),
    DOWNTIME_CATEGORY VARCHAR(50)
);

 
 CREATE TABLE FACT_MAINTENANCE (
    MAINTENANCE_ID BIGINT PRIMARY KEY,

    DATE_KEY INTEGER,
    PLANT_ID INTEGER,
    MACHINE_ID INTEGER,

    MAINTENANCE_TYPE VARCHAR(50),

    MAINTENANCE_START TIMESTAMP,
    MAINTENANCE_END TIMESTAMP,

    MAINTENANCE_HOURS DECIMAL(10,2),

    MAINTENANCE_COST DECIMAL(14,2),
    PARTS_COST DECIMAL(14,2),

    TECHNICIAN_ID INTEGER
);

