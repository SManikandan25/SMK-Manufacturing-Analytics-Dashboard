--Fact tables NULL check
SELECT
    COUNT_IF(PLANT_ID IS NULL) AS NULL_PLANT,
    COUNT_IF(LINE_ID IS NULL) AS NULL_LINE,
    COUNT_IF(MACHINE_ID IS NULL) AS NULL_MACHINE,
    COUNT_IF(PRODUCT_ID IS NULL) AS NULL_PRODUCT,
    COUNT_IF(DATE_KEY IS NULL) AS NULL_DATE
FROM FACT_PRODUCTION;

--Production business check
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_PRODUCTION
WHERE PLANNED_QTY <= 0
   OR PRODUCED_QTY <= 0
   OR GOOD_QTY < 0
   OR REJECTED_QTY < 0
   OR PRODUCED_QTY <> GOOD_QTY + REJECTED_QTY;

   --Quality business check
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_QUALITY
WHERE INSPECTION_COUNT <= 0
   OR PASSED_COUNT < 0
   OR FAILED_COUNT < 0
   OR INSPECTION_COUNT <> PASSED_COUNT + FAILED_COUNT;

--Downtime check
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_DOWNTIME
WHERE DOWNTIME_MINUTES <= 0
   OR DOWNTIME_END <= DOWNTIME_START;

--Maintenance check
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_MAINTENANCE
WHERE MAINTENANCE_HOURS <= 0
   OR MAINTENANCE_COST < 0
   OR PARTS_COST < 0
   OR MAINTENANCE_END <= MAINTENANCE_START;