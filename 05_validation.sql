USE DATABASE SMK_MANUFACTURING_DB;


--FOR DM_product
-- Check row counts
SELECT COUNT(*) FROM DIM_PLANT;
SELECT COUNT(*) FROM DIM_DATE;
SELECT COUNT(*) FROM DIM_PRODUCT;

-- Check product categories
SELECT
    PRODUCT_CATEGORY,
    COUNT(*) AS PRODUCT_COUNT
FROM DIM_PRODUCT
GROUP BY PRODUCT_CATEGORY;




--FOR DM_line
SELECT
    PLANT_ID,
    COUNT(*) AS LINE_COUNT
FROM DIM_LINE
GROUP BY PLANT_ID
ORDER BY PLANT_ID;

--FOR DM_machine
SELECT
    PLANT_ID,
    COUNT(*) AS MACHINE_COUNT
FROM DIM_MACHINE
GROUP BY PLANT_ID
ORDER BY PLANT_ID;

--FOR DM_shift
SELECT *
FROM DIM_SHIFT
ORDER BY SHIFT_ID;

--FOR DM_user_access
SELECT
    ROLE_NAME,
    COUNT(*) AS USER_COUNT
FROM DIM_USER_ACCESS
GROUP BY ROLE_NAME
ORDER BY ROLE_NAME;



--fact production
SELECT *
FROM FACT_PRODUCTION
ORDER BY PRODUCTION_ID;

SELECT
    SUM(PLANNED_QTY) AS TOTAL_PLANNED,
    SUM(PRODUCED_QTY) AS TOTAL_PRODUCED,
    SUM(GOOD_QTY) AS TOTAL_GOOD,
    SUM(REJECTED_QTY) AS TOTAL_REJECTED
FROM FACT_PRODUCTION;

-- FACT_PRODUCTION - Row Count
SELECT COUNT(*) AS TOTAL_ROWS
FROM FACT_PRODUCTION;

-- FACT_PRODUCTION - Date Range
SELECT
    MIN(DATE_KEY) AS START_DATE,
    MAX(DATE_KEY) AS END_DATE,
    COUNT(DISTINCT PLANT_ID) AS PLANTS,
    COUNT(DISTINCT LINE_ID) AS LINES,
    COUNT(DISTINCT MACHINE_ID) AS MACHINES,
    COUNT(DISTINCT PRODUCT_ID) AS PRODUCTS,
    COUNT(DISTINCT SHIFT_ID) AS SHIFTS
FROM FACT_PRODUCTION;

-- Produced = Good + Rejected
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_PRODUCTION
WHERE PRODUCED_QTY <> GOOD_QTY + REJECTED_QTY;

-- Check negative quantities
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_PRODUCTION
WHERE PLANNED_QTY <= 0
   OR PRODUCED_QTY <= 0
   OR GOOD_QTY <= 0
   OR REJECTED_QTY < 0;

   -- Check invalid Plant → Line mapping
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_PRODUCTION F
LEFT JOIN DIM_LINE L
    ON F.LINE_ID = L.LINE_ID
   AND F.PLANT_ID = L.PLANT_ID
WHERE L.LINE_ID IS NULL;

-- Check invalid Line → Machine mapping
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_PRODUCTION F
LEFT JOIN DIM_MACHINE M
    ON F.MACHINE_ID = M.MACHINE_ID
   AND F.LINE_ID = M.LINE_ID
WHERE M.MACHINE_ID IS NULL;

SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_PRODUCTION
WHERE GOOD_QTY < 0
   OR REJECTED_QTY < 0
   OR GOOD_QTY + REJECTED_QTY <> PRODUCED_QTY;

   -- FACT_PRODUCTION_TARGET- Row Count
SELECT COUNT(*) AS TOTAL_ROWS
FROM FACT_PRODUCTION_TARGET;

SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_PRODUCTION_TARGET
WHERE TARGET_QTY <= 0
   OR TARGET_COST < 0;

SELECT
    MIN(DATE_KEY) AS START_DATE,
    MAX(DATE_KEY) AS END_DATE,
    COUNT(DISTINCT PLANT_ID) AS PLANTS,
    COUNT(DISTINCT LINE_ID) AS LINES,
    COUNT(DISTINCT PRODUCT_ID) AS PRODUCTS
FROM FACT_PRODUCTION_TARGET;

-- FACT_Quality- Row Count
SELECT COUNT(*) AS TOTAL_ROWS
FROM FACT_QUALITY;
-- FACT_Quality- CHECK INVALID  ROW COUNT
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_QUALITY
WHERE INSPECTION_COUNT <> PASSED_COUNT + FAILED_COUNT;


--FACT DOWNTIME- ROW COUNT
SELECT COUNT(*) AS TOTAL_ROWS
FROM FACT_DOWNTIME;

--FACT DOWNTIME Duration check
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_DOWNTIME
WHERE DOWNTIME_MINUTES <= 0;

--FACT DOWNTIME Start → End validation
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_DOWNTIME
WHERE DATEDIFF(
          MINUTE,
          DOWNTIME_START,
          DOWNTIME_END
      ) <> DOWNTIME_MINUTES;

--FACT DOWNTIME Machine relationship
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_DOWNTIME D
LEFT JOIN DIM_MACHINE M
    ON D.MACHINE_ID = M.MACHINE_ID
   AND D.LINE_ID = M.LINE_ID
WHERE M.MACHINE_ID IS NULL;

--FACT DOWNTIME Plant → Line relationship
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_DOWNTIME D
LEFT JOIN DIM_LINE L
    ON D.LINE_ID = L.LINE_ID
   AND D.PLANT_ID = L.PLANT_ID
WHERE L.LINE_ID IS NULL;

--FACT MAINTANENCE  Row count validation

SELECT COUNT(*) AS TOTAL_ROWS
FROM FACT_MAINTENANCE;

--FACT MAINTANENCE Hours validation
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_MAINTENANCE
WHERE MAINTENANCE_HOURS <= 0;

--FACT MAINTANENCE Cost validation
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_MAINTENANCE
WHERE MAINTENANCE_COST < 0
   OR PARTS_COST < 0;

--FACT MAINTANENCE Date/time validation
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_MAINTENANCE
WHERE MAINTENANCE_END <= MAINTENANCE_START;

--FACT MAINTANENCE Machine relationship
SELECT COUNT(*) AS INVALID_ROWS
FROM FACT_MAINTENANCE M
LEFT JOIN DIM_MACHINE DM
    ON M.MACHINE_ID = DM.MACHINE_ID
WHERE DM.MACHINE_ID IS NULL;

